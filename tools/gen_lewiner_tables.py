#!/usr/bin/env python3
"""Writes src/TripoSR.Net/Mesh/LewinerTables.cs from scikit-image's `_marching_cubes_lewiner_luts.py` (BSD-3-Clause), the look-up tables of Lewiner et al.'s
marching cubes that the reference mesh was made with. A migration tool, run once; the C# file is committed.

The input is read as data (its assignments are parsed with `ast.literal_eval`), never executed.

    python3 -I tools/gen_lewiner_tables.py PATH/TO/_marching_cubes_lewiner_luts.py src/TripoSR.Net/Mesh/LewinerTables.cs
"""
import ast
import re
import sys

src, dst = sys.argv[1], sys.argv[2]
tree = ast.parse(open(src, encoding="utf-8").read(), src)
tables = {}
for node in tree.body:
    if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name) and node.targets[0].id.isupper():
        name = node.targets[0].id
        if name.startswith("EDGETORELATIVEPOS"):
            continue  # small explicit arrays, written by hand in the C# (they are not base64)
        value = ast.literal_eval(node.value)
        shape, text = value
        assert all(isinstance(d, int) for d in shape) and isinstance(text, str), name
        tables[name] = (shape, text)

order = [
    "CASESCLASSIC", "CASES", "TILING1", "TILING2", "TILING3_1", "TILING3_2", "TILING4_1", "TILING4_2", "TILING5", "TILING6_1_1", "TILING6_1_2", "TILING6_2",
    "TILING7_1", "TILING7_2", "TILING7_3", "TILING7_4_1", "TILING7_4_2", "TILING8", "TILING9", "TILING10_1_1", "TILING10_1_1_", "TILING10_1_2", "TILING10_2",
    "TILING10_2_", "TILING11", "TILING12_1_1", "TILING12_1_1_", "TILING12_1_2", "TILING12_2", "TILING12_2_", "TILING13_1", "TILING13_1_", "TILING13_2",
    "TILING13_2_", "TILING13_3", "TILING13_3_", "TILING13_4", "TILING13_5_1", "TILING13_5_2", "TILING14", "TEST3", "TEST4", "TEST6", "TEST7", "TEST10",
    "TEST12", "TEST13", "SUBCONFIG13",
]
missing, extra = set(order) - set(tables), set(tables) - set(order)
assert not missing and not extra, (missing, extra)

out = ["""// <auto-generated>
// By tools/gen_lewiner_tables.py from scikit-image's skimage/measure/_marching_cubes_lewiner_luts.py (scikit-image 0.26.0), which was generated from the
// look-up tables of Thomas Lewiner's C++ marching cubes. Do not edit by hand.
//
// Copyright (C) 2009-2022 the scikit-image team. BSD-3-Clause (https://github.com/scikit-image/scikit-image/blob/main/LICENSE.txt).
// </auto-generated>
namespace TripoSR.Mesh;

/// <summary>The tables of the marching cubes of Lewiner et al. (2003), as scikit-image ships them: each one a signed-byte array with its shape.</summary>
internal static class LewinerTables
{"""]
for n in order:
    shape, text = tables[n]
    b64 = re.sub(r"\s+", "", text)
    out.append(f'    public static readonly Lut {n} = new([{", ".join(map(str, shape))}], "{b64}");')
out.append("}")
with open(dst, "w", encoding="utf-8") as f:
    f.write("\n".join(out) + "\n")
print("wrote", dst, len(order), "tables")
for n in order:
    print(n, tables[n][0])
